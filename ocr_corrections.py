# ── 构造逐字符翻译表（str.translate 效率更高）─────────────────────────────────
_TRANS_TABLE = str.maketrans(CHAR_MAP)


def normalize_ocr_text(text: str) -> str:
    """
    对 OCR 原始文本应用字符修正。

    当前处理：
      - 按 CHAR_MAP 做字符级替换（繁简转换、形近字修正）

    若将来需要整词级修正，可在此扩展。
    """
    return text.translate(_TRANS_TABLE)
